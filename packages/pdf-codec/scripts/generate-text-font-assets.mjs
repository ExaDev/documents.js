#!/usr/bin/env node
// Regenerates src/assets/{carlito,caladea}-{regular,bold,italic,bolditalic}.ts from the vendored assets/fonts/{carlito,caladea}/*.ttf binaries.
//
// Run with `node scripts/generate-text-font-assets.mjs` after replacing a vendored font file (e.g. a licence-compatible update). Not part of `pnpm build`/`pnpm test` -- the generated .ts files are committed to the repository as ordinary source files, exactly like any other checked-in generated artifact, so the package never needs a filesystem read of a binary asset at runtime (see src/assets/stix-two-math-font.ts's own header comment for why that mattered for ESM/CJS parity).
//
// Unlike scripts/generate-math-font-asset.mjs (which embeds the STIX Two Math font's raw bytes as base64 directly), each font here is DEFLATE-compressed via fflate's deflateSync before base64-encoding, since these are ordinary TrueType text fonts with much more redundant, compressible table data (glyf/loca/hmtx/name tables) than the single small math font -- compressing first keeps the committed .ts source materially smaller. The runtime consumer inflates with fflate's own inflateSync before parsing the sfnt.
//
// This script is deliberately outside tsconfig.json's "include" and eslint.config.ts's linted set (see the "scripts" entry in both), matching the existing precedent for generate-math-font-asset.mjs and test/smoke.test.mjs: a standalone maintenance utility, not part of the shipped src/ program.

import { deflateSync } from 'fflate';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fontsDir = join(here, '..', 'assets', 'fonts');
const outputDir = join(here, '..', 'src', 'assets');

const FACES = [
  { family: 'carlito', face: 'regular', sourceFile: 'Carlito-Regular.ttf', exportName: 'CARLITO_REGULAR_FONT_DEFLATED_BASE64' },
  { family: 'carlito', face: 'bold', sourceFile: 'Carlito-Bold.ttf', exportName: 'CARLITO_BOLD_FONT_DEFLATED_BASE64' },
  { family: 'carlito', face: 'italic', sourceFile: 'Carlito-Italic.ttf', exportName: 'CARLITO_ITALIC_FONT_DEFLATED_BASE64' },
  { family: 'carlito', face: 'bolditalic', sourceFile: 'Carlito-BoldItalic.ttf', exportName: 'CARLITO_BOLDITALIC_FONT_DEFLATED_BASE64' },
  { family: 'caladea', face: 'regular', sourceFile: 'Caladea-Regular.ttf', exportName: 'CALADEA_REGULAR_FONT_DEFLATED_BASE64' },
  { family: 'caladea', face: 'bold', sourceFile: 'Caladea-Bold.ttf', exportName: 'CALADEA_BOLD_FONT_DEFLATED_BASE64' },
  { family: 'caladea', face: 'italic', sourceFile: 'Caladea-Italic.ttf', exportName: 'CALADEA_ITALIC_FONT_DEFLATED_BASE64' },
  { family: 'caladea', face: 'bolditalic', sourceFile: 'Caladea-BoldItalic.ttf', exportName: 'CALADEA_BOLDITALIC_FONT_DEFLATED_BASE64' },
];

for (const { family, face, sourceFile, exportName } of FACES) {
  const sourcePath = join(fontsDir, family, sourceFile);
  const outputPath = join(outputDir, `${family}-${face}.ts`);

  const fontBytes = readFileSync(sourcePath);
  const deflated = deflateSync(fontBytes);
  const base64 = Buffer.from(deflated).toString('base64');

  const header = `// AUTO-GENERATED by scripts/generate-text-font-assets.mjs from assets/fonts/${family}/${sourceFile} -- do not hand-edit.
// Regenerate with: node scripts/generate-text-font-assets.mjs
//
// The font's bytes are DEFLATE-compressed (fflate's raw deflateSync, RFC 1951, no zlib wrapper) then embedded as a base64 string (rather than read from disk at runtime via a path relative to import.meta.url/__dirname), so this module resolves identically from source, from the built ESM bundle, and from the built CJS bundle, with no dual-module path-resolution logic and no dependency on the published package's on-disk layout. A consumer must inflate with fflate's inflateSync before parsing the sfnt. See assets/fonts/${family}/NOTICE.md for this font's own licence (OFL-1.1) and provenance.
export const ${exportName} =
`;

  const literal = `  '${base64}';\n`;

  writeFileSync(outputPath, header + literal, 'utf8');
  console.log(
    `Wrote ${outputPath} (${fontBytes.length} bytes source -> ${deflated.length} bytes deflated -> ${base64.length} base64 chars)`,
  );
}

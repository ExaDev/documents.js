#!/usr/bin/env node
// Regenerates src/assets/stix-two-math-font.ts from the vendored assets/fonts/STIXTwoMath-Regular.otf binary.
//
// Run with `node scripts/generate-math-font-asset.mjs` after replacing the vendored font file (e.g. a licence-compatible update). Not part of `pnpm build`/`pnpm test` -- the generated .ts file is committed to the repository as an ordinary source file, exactly like any other checked-in generated artifact, so the package never needs a filesystem read of a binary asset at runtime (see src/assets/stix-two-math-font.ts's own header comment for why that mattered for ESM/CJS parity).
//
// This script is deliberately outside tsconfig.json's "include" and eslint.config.ts's linted set (see the "scripts" entry in both), matching the existing precedent for test/smoke.test.mjs: a standalone maintenance utility, not part of the shipped src/ program.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = join(here, '..', 'assets', 'fonts', 'STIXTwoMath-Regular.otf');
const outputPath = join(here, '..', 'src', 'assets', 'stix-two-math-font.ts');

const fontBytes = readFileSync(sourcePath);
const base64 = fontBytes.toString('base64');

const header = `// AUTO-GENERATED by scripts/generate-math-font-asset.mjs from assets/fonts/STIXTwoMath-Regular.otf -- do not hand-edit.
// Regenerate with: node scripts/generate-math-font-asset.mjs
//
// The font's bytes are embedded as a base64 string (rather than read from disk at runtime via a path relative to import.meta.url/__dirname) so this module resolves identically from source, from the built ESM bundle, and from the built CJS bundle, with no dual-module path-resolution logic and no dependency on the published package's on-disk layout. See assets/fonts/NOTICE.md for the font's own licence (OFL-1.1) and provenance.
export const STIX_TWO_MATH_FONT_BASE64 =
`;

const literal = `  '${base64}';\n`;

writeFileSync(outputPath, header + literal, 'utf8');
console.log(`Wrote ${outputPath} (${fontBytes.length} bytes source -> ${base64.length} base64 chars)`);

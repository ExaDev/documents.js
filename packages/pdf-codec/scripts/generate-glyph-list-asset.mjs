#!/usr/bin/env node
// Regenerates src/glyph-data/adobe-glyph-list.ts from the vendored assets/agl/glyphlist.txt and assets/agl/zapfdingbats.txt.
//
// Run with `node scripts/generate-glyph-list-asset.mjs` after replacing either vendored list. Not part of `pnpm build`/`pnpm test`: the generated module is committed like the src/assets/ font modules, so the package never reads a file at runtime. It lives in src/glyph-data/ rather than src/assets/ because the read path needs it, and src/read-graph.test.ts keeps every src/assets/ module (the write path's font binaries) out of the read path's module graph. Each list is carried as one string of `name;HEX[ HEX...]` entries separated by newlines, exactly the entry lines of the source file with its comment block dropped; src/glyph-names.ts parses it on first use.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const aglDir = join(here, '..', 'assets', 'agl');
const outputPath = join(here, '..', 'src', 'glyph-data', 'adobe-glyph-list.ts');

const ENTRY = /^[A-Za-z0-9_.]+;[0-9A-F]{4}( [0-9A-F]{4})*$/;

function entries(file) {
  const lines = readFileSync(join(aglDir, file), 'utf8')
    .split('\n')
    .filter((line) => line !== '' && !line.startsWith('#'));
  for (const line of lines) {
    if (!ENTRY.test(line)) {
      throw new Error(`${file}: unexpected entry ${JSON.stringify(line)}`);
    }
  }
  return lines;
}

const glyphList = entries('glyphlist.txt');
const zapfDingbats = entries('zapfdingbats.txt');
const literal = (lines) => `  ${JSON.stringify(lines.join('\n'))};\n`;

const header = `// AUTO-GENERATED by scripts/generate-glyph-list-asset.mjs from assets/agl/glyphlist.txt and assets/agl/zapfdingbats.txt. Do not hand-edit.
// Regenerate with: node scripts/generate-glyph-list-asset.mjs
//
// The Adobe Glyph List and the ITC Zapf Dingbats Glyph List, version 2.0, from https://github.com/adobe-type-tools/agl-aglfn. Copyright 2002-2019 Adobe (http://www.adobe.com/), redistributed under the BSD 3-Clause licence reproduced in assets/agl/LICENSE.md: redistributions must retain that copyright notice, this list of conditions and the disclaimer, and the name of Adobe may not be used to endorse or promote products derived from it without specific prior written permission. THIS DATA IS PROVIDED BY THE COPYRIGHT HOLDERS AND CONTRIBUTORS "AS IS" AND ANY EXPRESS OR IMPLIED WARRANTIES ARE DISCLAIMED; see the licence for the full disclaimer.
//
// Each constant is the list's entry lines, \`name;HEX[ HEX...]\`, joined by newlines.
`;

writeFileSync(
  outputPath,
  `${header}export const ADOBE_GLYPH_LIST =\n${literal(glyphList)}\nexport const ZAPF_DINGBATS_GLYPH_LIST =\n${literal(zapfDingbats)}`,
  'utf8',
);
console.log(`Wrote ${outputPath} (${glyphList.length} + ${zapfDingbats.length} entries)`);

#!/usr/bin/env node
// Regenerates src/scan/entity-table.ts from the vendored assets/html-entities/entities.json.
//
// Run with `node scripts/generate-entity-table.mjs` after replacing the vendored entities.json (e.g. a WHATWG Living Standard update). Not part of `pnpm build`/`pnpm test` -- the generated .ts file is committed to the repository as an ordinary source file, exactly like any other checked-in generated artifact, mirroring pdf-codec's own scripts/generate-math-font-asset.mjs pattern (see that script's own header comment) so this package never needs a filesystem read of the JSON asset at runtime.
//
// This script is deliberately outside tsconfig.json's "include" and eslint.config.ts's linted set (see the "scripts" entry in both), matching the existing precedent for test/smoke.test.mjs: a standalone maintenance utility, not part of the shipped src/ program.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = join(here, '..', 'assets', 'html-entities', 'entities.json');
const outputPath = join(here, '..', 'src', 'scan', 'entity-table.ts');

/** @type {Record<string, { codepoints: number[]; characters: string }>} */
const entities = JSON.parse(readFileSync(sourcePath, 'utf8'));

// CommonMark's own "Entity and numeric character references" section (assets/commonmark/spec.txt) requires the trailing ';' unconditionally: "Although HTML5 does accept some entity references without a trailing semicolon (such as &copy), these are not recognized here, because it makes the grammar too ambiguous." So this table omits the WHATWG list's own semicolon-optional legacy aliases entirely -- an entry this package's scanner can never look up would just be dead weight.
const entries = Object.entries(entities)
  .filter(([name]) => name.endsWith(';'))
  .map(([name, entity]) => [name.slice(1, -1), entity.characters])
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const header = `// AUTO-GENERATED by scripts/generate-entity-table.mjs from assets/html-entities/entities.json -- do not hand-edit.
// Regenerate with: node scripts/generate-entity-table.mjs
//
// Keyed by entity name WITHOUT the leading '&' or trailing ';' (e.g. 'amp', 'nbsp', 'AElig') -- every key in this table is semicolon-terminated in the original WHATWG list, the only form CommonMark's own Entity references section recognises. See assets/html-entities/NOTICE.md for the source's own licence and provenance.
export const HTML_ENTITY_TABLE: Readonly<Record<string, string>> = {
`;

const body = entries.map(([name, characters]) => `  ${JSON.stringify(name)}: ${JSON.stringify(characters)},`).join('\n');

const footer = '\n};\n';

writeFileSync(outputPath, header + body + footer, 'utf8');
console.log(`Wrote ${outputPath} (${String(entries.length)} entries from ${String(Object.keys(entities).length)} total WHATWG names)`);

/**
 * Resolves the name a document gives its own encoding to one {@link decodeText} can decode under.
 *
 * Matching follows the Encoding Standard: the name is stripped of leading and trailing ASCII whitespace and lowercased before lookup, so "  UTF-8 " and "utf-8" are the same label. A name decodeText cannot decode, a legacy multi-byte encoding or something unrecognised entirely, resolves to `undefined` rather than to an approximation.
 * @param label - The declared encoding name, however the document spelled it.
 * @returns The encoding to decode under, or `undefined` when the name names nothing decodeText decodes.
 */
export function resolveEncodingLabel(
  label: string,
): TextEncodingLabel | undefined {
  return ENCODING_LABELS.get(label.trim().toLowerCase());
}
